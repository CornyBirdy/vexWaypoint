// Regenerates js/changelog.js (the in-app changelog) from CHANGELOG.md. Run: node tools/make-changelog.js
'use strict';
const fs = require('fs');
const path = require('path');

/** CHANGELOG.md -> [{title, sections: [{name, items: [{text, sub: [text]}]}]}] */
function parse(md) {
  const releases = [];
  let rel = null;
  let sec = null;
  let item = null;
  let sub = null; // the sub-bullet being continued, or null
  const section = (name) => {
    sec = { name, items: [] };
    rel.sections.push(sec);
    item = sub = null;
  };
  for (const raw of md.split(/\r?\n/)) {
    const line = raw.replace(/\s+$/, '');
    let m;
    if ((m = /^## (.+)$/.exec(line))) {
      rel = { title: m[1].trim(), sections: [] };
      releases.push(rel);
      sec = item = sub = null;
    } else if (!rel) continue;
    else if ((m = /^### (.+)$/.exec(line))) section(m[1].trim());
    else if ((m = /^- (.+)$/.exec(line))) {
      if (!sec) section('');
      item = { text: m[1].trim(), sub: [] };
      sec.items.push(item);
      sub = null;
    } else if ((m = /^  - (.+)$/.exec(line)) && item) {
      item.sub.push(m[1].trim());
      sub = item.sub.length - 1;
    } else if (/^    \S/.test(line) && item && sub !== null) item.sub[sub] += ' ' + line.trim();
    else if (/^  \S/.test(line) && item) item.text += ' ' + line.trim();
  }
  return releases;
}

function render(md) {
  return (
    '/* Generated by tools/make-changelog.js from CHANGELOG.md - do not edit by hand. */\n' +
    "(function () {\n  'use strict';\n  const NS = (globalThis.VSim = globalThis.VSim || {});\n  NS.CHANGELOG = " +
    JSON.stringify(parse(md), null, 2).replace(/\n/g, '\n  ') +
    ';\n})();\n'
  );
}

module.exports = { parse, render };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  fs.writeFileSync(path.join(root, 'js', 'changelog.js'), render(fs.readFileSync(path.join(root, 'CHANGELOG.md'), 'utf8')));
  console.log('wrote js/changelog.js');
}
