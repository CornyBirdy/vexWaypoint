// Regenerates examples/ and js/examples.js. Run: node tools/make-examples.js
'use strict';
const fs = require('fs');
const path = require('path');
for (const f of ['lemlib', 'paths']) require(path.join('..', 'js', f + '.js'));
const V = globalThis.VSim;

const project = {
  appVersion: '0.7.0',
  format: 'LemLib v0.5 (inch)',
  uid: 'example-project',
  gc: { robotWidth: 12, robotHeight: 12, robotIsHolonomic: false, showRobot: true, pointDensity: 2, controlMagnetDistance: 5.7 },
  paths: [
    {
      name: 'Path 1',
      uid: 'example-path',
      visible: true,
      lock: false,
      pc: { speedLimit: { minLimit: { value: 20, label: '20' }, topLimit: { value: 100, label: '100' } }, bentRate: { value: 0.1, label: '0.1' } },
      segments: [
        { controls: [{ x: -36, y: -36 }, { x: -18, y: -36 }, { x: -30, y: -14 }, { x: -12, y: -12 }] },
      ],
    },
  ],
};
const parsed = V.parsePathFile('example.jerryio', JSON.stringify(project));
const pts = parsed.paths[0].points;
const txt = pts.map((p) => `${p.x.toFixed(3)}, ${p.y.toFixed(3)}, ${p.v.toFixed(3)}`).join('\n') +
  '\nendData\n#PATH.JERRYIO-DATA ' + JSON.stringify(project) + '\n';

fs.writeFileSync('examples/example.jerryio', JSON.stringify(project, null, 2) + '\n');
fs.writeFileSync('examples/example.txt', txt);

const cpp = `#include "main.h"

// Path exported from path.jerryio. Drop example.txt onto the sim and this
// name (file name with the dot turned into _) becomes available.
ASSET(example_txt)

void autonomous() {
    // 0, 0, 0 is wherever the start pose is set in the sim
    chassis.setPose(0, 0, 0);

    chassis.moveToPoint(0, 24, 3000);               // drive forward 24 in
    chassis.turnToHeading(90, 1500);                // face right
    chassis.moveToPose(24, 24, 90, 3000, {.lead = 0.5});
    chassis.waitUntilDone();

    // follow a jerry.io path: lookahead 15 in, 4 s timeout
    chassis.follow(example_txt, 15, 4000);
    chassis.waitUntilDone();

    chassis.turnToPoint(0, 0, 1000);                // look at the centre goal
    chassis.swingToHeading(180, lemlib::DriveSide::LEFT, 1500);
    chassis.moveToPoint(24, 48, 3000, {.forwards = false, .maxSpeed = 80});
    chassis.waitUntilDone();
}
`;
fs.writeFileSync('examples/example_auton.cpp', cpp);

const js = `/* Generated by tools/make-examples.js - do not edit by hand. */
(function () {
  'use strict';
  const NS = (globalThis.VSim = globalThis.VSim || {});
  NS.EXAMPLES = {
    code: ${JSON.stringify(cpp)},
    pathName: 'example.txt',
    pathText: ${JSON.stringify(txt)},
  };
})();
`;
fs.writeFileSync('js/examples.js', js);
console.log('wrote examples/ and js/examples.js (' + pts.length + ' path points)');
